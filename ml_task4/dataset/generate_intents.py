def random_error(text, error_prob=0.05):
    if not text:
        return text
    chars = list(text)
    for i in range(len(chars)):
        if random.random() < error_prob:
            t = random.choice(['substitute', 'delete', 'insert'])
            if t == 'substitute':
                chars[i] = random.choice('йцукенгшщзхъфывапролджэячсмитьбюё')
            elif t == 'delete':
                chars[i] = ''
            elif t == 'insert':
                chars[i] += random.choice('йцукенгшщзхъфывапролджэячсмитьбюё')
    return ''.join(chars)

def apply_synonyms(text, synonyms_dict):
    words = text.split()
    new_words = []
    for w in words:
        replaced = False
        for key, variants in synonyms_dict.items():
            if w.lower() == key:
                new_words.append(random.choice(variants))
                replaced = True
                break
        if not replaced:
            new_words.append(w)
    return ' '.join(new_words)

def generate_variations(base_phrases, count=500, syn_dict=SYNONYMS, intros=INTROS):
    variations = set()
    for phrase in base_phrases:
        variations.add(phrase)
    
    attempts = 0
    max_attempts = count * 10
    while len(variations) < count and attempts < max_attempts:
        attempts += 1
        base = random.choice(base_phrases)
        if random.random() < 0.7:
            base = apply_synonyms(base, syn_dict)
        if random.random() < 0.5:
            intro = random.choice(intros)
            if random.random() < 0.5:
                base = intro + " " + base
            else:
                base = base + " " + intro
        if random.random() < 0.3 and len(base.split()) > 2:
            words = base.split()
            if len(words) >= 3:
                i = random.randint(0, len(words)-2)
                words[i], words[i+1] = words[i+1], words[i]
                base = ' '.join(words)
        if random.random() < 0.6 and not base.endswith('?'):
            base += '?'
        elif random.random() < 0.3 and base.endswith('?'):
            base = base[:-1] + '.'
        variations.add(base)
    
    final_list = list(variations)
    if len(final_list) > count:
        final_list = random.sample(final_list, count)
    error_count = int(count * 0.05)
    if error_count > 0:
        error_indices = random.sample(range(len(final_list)), error_count)
        for idx in error_indices:
            final_list[idx] = random_error(final_list[idx], error_prob=0.05)
    return final_list

